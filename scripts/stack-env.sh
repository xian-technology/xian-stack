stack_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

resolve_repo_dir() {
  local name="$1"
  local explicit_value="${2:-}"
  local sibling_path="${stack_root}/../${name}"

  if [[ -n "${explicit_value}" ]]; then
    printf '%s\n' "${explicit_value}"
    return
  fi

  if [[ -d "${sibling_path}" ]]; then
    printf '%s\n' "${sibling_path}"
    return
  fi

  printf '%s\n' "${sibling_path}"
}

