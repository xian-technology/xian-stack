require_stack_paths() {
  local required_paths=(
    "${XIAN_CLI_DIR}"
    "${XIAN_ABCI_DIR}"
    "${XIAN_CONFIGS_DIR}"
    "${XIAN_CONTRACTING_DIR}"
    "${XIAN_PY_DIR}"
    "${XIAN_CONTRACTS_DIR}"
  )

  for path in "${required_paths[@]}"; do
    if [[ ! -d "${path}" ]]; then
      printf 'missing required directory: %s\n' "${path}" >&2
      return 1
    fi
  done
}

require_docker() {
  if ! command -v docker >/dev/null 2>&1; then
    printf 'docker is required but not installed\n' >&2
    return 1
  fi

  docker compose version >/dev/null
}

require_uv() {
  if ! command -v uv >/dev/null 2>&1; then
    printf 'uv is required but not installed\n' >&2
    return 1
  fi
}

prepare_stack_dirs() {
  mkdir -p "${XIAN_COMETBFT_HOME}" "${XIAN_BDS_DATA_DIR}" "${XIAN_CONTRACTS_DIR}"
}
